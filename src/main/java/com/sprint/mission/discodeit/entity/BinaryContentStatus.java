package com.sprint.mission.discodeit.entity;

/**
 * 바이너리 콘텐츠의 처리 상태를 정의하는 열거형입니다.
 * 
 * <p>파일 업로드 과정에서 발생할 수 있는 다양한 상태를 표현하며,
 * 시스템이 파일의 현재 상황을 추적하는 데 사용됩니다.</p>
 * 
 * @author HuInDoL
 * @since 1.0.0
 */
public enum BinaryContentStatus {
    /**
     * 파일이 현재 처리 중인 상태입니다.
     * 
     * <p>업로드가 시작되었지만 아직 완료되지 않은 상태를 나타냅니다.</p>
     */
    PROCESSING,
    
    /**
     * 파일 처리가 성공적으로 완료된 상태입니다.
     * 
     * <p>업로드와 저장이 정상적으로 완료되어 사용 가능한 상태입니다.</p>
     */
    SUCCESS,
    
    /**
     * 파일 처리 중 오류가 발생한 상태입니다.
     * 
     * <p>업로드 실패, 저장 실패 등의 이유로 처리할 수 없는 상태입니다.</p>
     */
    FAIL
}
