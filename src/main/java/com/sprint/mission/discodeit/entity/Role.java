package com.sprint.mission.discodeit.entity;

/**
 * 사용자의 권한 역할을 정의하는 열거형입니다.
 * 
 * <p>시스템 내에서 사용자가 수행할 수 있는 작업의 범위를 결정하며,
 * 계층적 구조로 설계되어 상위 권한이 하위 권한을 포함합니다.</p>
 * 
 * <p>권한 계층 구조:</p>
 * <ul>
 *   <li>ADMIN: 모든 권한을 가진 최고 관리자</li>
 *   <li>CHANNEL_MANAGER: 채널 관리 권한을 가진 중간 관리자</li>
 *   <li>USER: 기본 사용자 권한</li>
 * </ul>
 * 
 * @author HuInDoL
 * @since 1.0.0
 */
public enum Role {
    /**
     * 시스템 최고 관리자 권한입니다.
     * 
     * <p>모든 기능에 대한 접근 권한을 가지며, 사용자 관리, 시스템 설정 등을 수행할 수 있습니다.</p>
     */
    ADMIN,
    
    /**
     * 채널 관리자 권한입니다.
     * 
     * <p>채널 생성, 수정, 삭제 및 사용자 초대 등의 권한을 가집니다.</p>
     */
    CHANNEL_MANAGER,
    
    /**
     * 일반 사용자 권한입니다.
     * 
     * <p>기본적인 채팅 및 파일 공유 기능을 사용할 수 있습니다.</p>
     */
    USER
}
